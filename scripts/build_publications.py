def youtube_id(value):
    """Accept a bare video ID or any common YouTube URL."""
    m = re.search(r"(?:v=|youtu\.be/|embed/|shorts/)([\w-]{11})", value)
    return m.group(1) if m else value.strip()


def slug(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:48]


def link_label(url):
    return "arXiv" if "arxiv.org" in url else "Paper"


def clip(path, poster=None):
    """A looping muted clip for video files, otherwise a lazy image (GIF, PNG, JPG)."""
    src = escape(path)
    if path.lower().endswith((".mp4", ".webm")):
        poster = f' poster="{escape(poster)}"' if poster else ""
        return f'<video src="{src}"{poster} autoplay muted loop playsinline preload="metadata" aria-hidden="true"></video>'
    return f'<img src="{src}" alt="" loading="lazy">'


def figure(p, indent):
    """Visual in the right-hand column of a paper; media.js enlarges it with its caption on click.
    With `figure_dark` the light/dark versions follow the visitor's theme."""
    caption = f"<figcaption>{escape(p['figure_caption'])}</figcaption>" if p.get("figure_caption") else ""
    media = clip(p["figure"], p.get("figure_poster"))
    if p.get("figure_dark"):
        media = (f'<div class="only-light">{media}</div>'
                 f'<div class="only-dark">{clip(p["figure_dark"], p.get("figure_dark_poster"))}</div>')
    return (f'{indent}<figure class="pub-figure"><a class="figure-zoom" href="{escape(p["figure"])}" '
            f'aria-label="Enlarge figure">{media}</a>{caption}</figure>')


ASCII = str.maketrans({"ø": "o", "Ø": "O", "æ": "ae", "Æ": "Ae", "å": "aa", "Å": "Aa"})


def split_authors(authors):
    """'W Lehn-Schiøler, MR Kjær, et al.' -> ([('Lehn-Schiøler', 'W'), ('Kjær', 'MR')], True)."""
    names, et_al = [], False
    for a in (x.strip() for x in authors.split(",")):
        if a.rstrip(".") == "et al":
            et_al = True
        else:
            initials, surname = a.split(" ", 1)
            names.append((surname, initials))
    return names, et_al


def person(surname, initials):
    return f"{surname}, {' '.join(i + '.' for i in initials)}"


def arxiv_id(p):
    m = re.search(r"arxiv\.org/abs/([\w.]+)", p.get("url", ""))
    return m.group(1) if m else None


def cite_key(p):
    surname = split_authors(p["authors"])[0][0][0].translate(ASCII)
    word = next((w for w in re.findall(r"[A-Za-z]+", p["title"]) if len(w) > 3), "paper")
    return re.sub(r"[^a-z]", "", surname.lower()) + str(p["year"]) + word.lower()


def bibtex(p, preprint):
    """BibTeX from the entry's `bib` fields (type, journal/booktitle, volume, number, pages, doi, note)."""
    bib = dict(p.get("bib") or {})
    kind = bib.pop("type", "misc" if preprint else "article")
    names, et_al = split_authors(p["authors"])
    fields = {
        # Brace all-caps words (EEG, SPEED) so BibTeX styles keep their case
        "title": re.sub(r"\b([A-Z]{2,}[\w-]*)", r"{\1}", p["title"]),
        "author": " and ".join(person(*n) for n in names) + (" and others" if et_al else ""),
        **{k: bib[k] for k in ("journal", "booktitle", "volume", "number", "pages") if k in bib},
        "year": p["year"],
        **{k: bib[k] for k in ("note", "doi") if k in bib},
    }
    if arxiv_id(p):
        fields.update(eprint=arxiv_id(p), archivePrefix="arXiv")
    if p.get("url"):
        fields["url"] = p["url"]
    body = ",\n".join(f"  {k:<13} = {{{v}}}" for k, v in fields.items())
    return f"@{kind}{{{cite_key(p)},\n{body}\n}}"


def reference(p, preprint):
    """APA-style plain-text reference."""
    bib = p.get("bib") or {}
    names, et_al = split_authors(p["authors"])
    people = [person(*n) for n in names]
    if et_al:
        authors = ", ".join(people) + ", et al."
    elif len(people) > 1:
        authors = ", ".join(people[:-1]) + ", & " + people[-1]
    else:
        authors = people[0]
    ref = f"{authors} ({p['year']}). {p['title']}."
    kind = bib.get("type", "misc" if preprint else "article")
    if kind == "article":
        ref += f" {bib['journal']}"
        ref += f", {bib['volume']}" if "volume" in bib else ""
        ref += f"({bib['number']})" if "number" in bib else ""
        ref += f", {str(bib['pages']).replace('--', '–')}" if "pages" in bib else ""
        ref += "."
    elif kind == "inproceedings":
        ref += f" In {bib['booktitle']}."
    elif arxiv_id(p):
        ref += f" arXiv preprint arXiv:{arxiv_id(p)}."
    if bib.get("note"):
        ref += f" {bib['note']}."
    link = f"https://doi.org/{bib['doi']}" if bib.get("doi") else p.get("url")
    return f"{ref} {link}" if link else ref


def cite_panel(p, preprint, panel_id, indent):
    block = ('<div class="cite-block"><div class="cite-head"><span>{label}</span>'
             '<button type="button" class="copy">Copy</button></div>{text}</div>')
    return (
        f'{indent}<div class="cite-panel" id="{panel_id}" hidden>'
        + block.format(label="Reference", text=f'<p class="cite-text">{escape(reference(p, preprint))}</p>')
        + block.format(label="BibTeX", text=f'<pre class="cite-text">{escape(bibtex(p, preprint))}</pre>')
        + "</div>"
    )


def pub_item(p, default_tag=None, summary=False, indent="                    ", heading="h3"):
    i1, i2, i3 = indent, indent + "    ", indent + "        "
    tag = p.get("tag", default_tag)
    preprint = default_tag == "Preprint"
    authors = escape(p["authors"]).replace(OWNER, f"<strong>{OWNER}</strong>")
    title = escape(p["title"])
    if p.get("url"):
        title = f'<a href="{escape(p["url"])}" target="_blank" rel="noopener noreferrer">{title}</a>'

    badges = []
    if tag:
        badges.append(f'<span class="pub-tag">{escape(tag)}</span>')
    if p.get("citations"):
        n = p["citations"]
        badges.append(f'<span class="pub-citations">{n} citation{"s" if n != 1 else ""}</span>')
    badges = f' <span class="pub-badges">{"".join(badges)}</span>' if badges else ""

    chips = []
    if p.get("url"):
        chips.append((p["url"], link_label(p["url"])))
    for key, label in (("pdf", "PDF"), ("code", "Code"), ("project", "Project page"),
                       ("poster", "Poster"), ("slides", "Slides")):
        if p.get(key):
            chips.append((p[key], label))
    chip_html = [
        f'<a class="chip" href="{escape(href)}" target="_blank" rel="noopener noreferrer">{label}</a>'
        for href, label in chips
    ]
    player = None
    if p.get("video"):
        vid = youtube_id(p["video"])
        player = f"player-{slug(p['title'])}"
        chip_html.append(
            f'<a class="chip" href="https://www.youtube.com/watch?v={escape(vid)}" data-yt="{escape(vid)}" '
            f'data-title="{escape(p["title"])}" aria-controls="{player}" aria-expanded="false" '
            f'target="_blank" rel="noopener noreferrer">▶ Video</a>'
        )
    cite = f"cite-{slug(p['title'])}"
    chip_html.append(f'<button type="button" class="chip" aria-controls="{cite}" aria-expanded="false">Cite</button>')

    cls = "pub has-figure" if p.get("figure") else "pub"
    lines = [
        f'{i1}<li class="{cls}">',
        f'{i2}<span class="pub-year">{p["year"]}</span>',
        f"{i2}<div>",
        f'{i3}<{heading} class="pub-title">{title}</{heading}>',
    ]
    if summary and p.get("summary"):
        lines.append(f'{i3}<p class="pub-summary">{escape(p["summary"])}</p>')
    lines += [
        f'{i3}<p class="pub-authors">{authors}</p>',
        f'{i3}<p class="pub-venue">{escape(p.get("web_venue", p["venue"]))}{badges}</p>',
    ]
    if chip_html:
        lines.append(f'{i3}<div class="chips">' + "".join(chip_html) + "</div>")
    lines.append(f"{i2}</div>")
    if p.get("figure"):
        lines.append(figure(p, i2))
    # Full-width rows under the paper, spanning the text and figure columns
    if player:
        lines.append(f'{i2}<div class="pub-player" id="{player}" hidden></div>')
    lines.append(cite_panel(p, preprint, cite, i2))
    lines.append(f"{i1}</li>")
    return "\n".join(lines)


def group(title, pubs, default_tag=None):
    items = "\n".join(pub_item(p, default_tag, indent="                        ", heading="h4") for p in pubs)
    return (
        '                <div class="pub-group">\n'
        f'                    <h3 class="pub-group-title">{title}</h3>\n'
        '                    <ol class="pub-list">\n'
        f"{items}\n"
        "                    </ol>\n"
        "                </div>\n"
    )


def selected_publications(data):
    featured = [(p, "Preprint") for p in data["preprints"] if p.get("featured")]
    featured += [(p, None) for p in data["peer_reviewed"] if p.get("featured")]
    featured.sort(key=lambda x: (-x[0]["year"], x[1] is not None))   # newest first, published before preprints
    items = "\n".join(pub_item(p, tag, summary=True, indent="                    ") for p, tag in featured)
    return (
        '                <ol class="pub-list">\n'
        f"{items}\n"
        "                </ol>\n"
    )


def media_card(m, indent):
    i1, i2, i3 = indent, indent + "    ", indent + "        "
    where = " · ".join(escape(str(m[k])) for k in ("kind", "venue", "date", "note") if m.get(k))
    label = escape(m["title"])
    if m.get("youtube"):
        vid = youtube_id(m["youtube"])
        player = (
            f'{i2}<a class="video" href="https://www.youtube.com/watch?v={escape(vid)}" data-yt="{escape(vid)}" '
            f'aria-label="Play: {label}" target="_blank" rel="noopener noreferrer">\n'
            f'{i3}<img src="https://i.ytimg.com/vi/{escape(vid)}/maxresdefault.jpg" alt="" loading="lazy" '
            f'onerror="this.onerror=null;this.src=\'https://i.ytimg.com/vi/{escape(vid)}/hqdefault.jpg\'">\n'
        )
    elif m.get("link"):
        # Hosted elsewhere (e.g. IDA Play): the poster links out
        player = (
            f'{i2}<a class="video" href="{escape(m["link"])}" aria-label="Watch: {label} (opens in a new tab)" '
            'target="_blank" rel="noopener noreferrer">\n'
        )
    else:
        player = f'{i2}<a class="video" href="{escape(m["file"])}" data-src="{escape(m["file"])}" aria-label="Play: {label}">\n'
    if not m.get("youtube") and m.get("poster"):
        player += f'{i3}<img src="{escape(m["poster"])}" alt="" loading="lazy">\n'
    player += f'{i3}<span class="play"></span>\n{i2}</a>\n'
    return (
        f'{i1}<article class="media-item">\n'
        + player
        + f"{i2}<h3>{label}</h3>\n"
        + (f"{i2}<p>{where}</p>\n" if where else "")
        + f"{i1}</article>"
    )


def media_grid(items, indent):
    cards = "\n".join(media_card(m, indent + "    ") for m in items)
    return f'{indent}<div class="media-grid">\n{cards}\n{indent}</div>\n'


