def youtube_id(value):
    """Accept a bare video ID or any common YouTube URL."""
    m = re.search(r"(?:v=|youtu\.be/|embed/|shorts/)([\w-]{11})", value)
    return m.group(1) if m else value.strip()


def slug(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:48]


def link_label(url):
    return "arXiv" if "arxiv.org" in url else "Paper"


def teaser(path, indent):
    src = escape(path)
    if path.lower().endswith((".mp4", ".webm")):
        media = f'<video src="{src}" autoplay muted loop playsinline preload="metadata" aria-hidden="true"></video>'
    else:
        media = f'<img src="{src}" alt="" loading="lazy">'
    return f'{indent}<div class="pub-teaser">{media}</div>'


def pub_item(p, default_tag=None, summary=False, indent="                    ", heading="h3"):
    i1, i2, i3 = indent, indent + "    ", indent + "        "
    tag = p.get("tag", default_tag)
    authors = escape(p["authors"]).replace(OWNER, f"<strong>{OWNER}</strong>")
    title = escape(p["title"])
    if p.get("url"):
        title = f'<a href="{escape(p["url"])}" target="_blank" rel="noopener noreferrer">{title}</a>'

    badges = []
    if tag:
        badges.append(f'<span class="pub-tag">{escape(tag)}</span>')
    if p.get("citations"):
        n = p["citations"]
        badges.append(f'<span class="pub-citations">{n} citation{"s" if n != 1 else ""}</span>')
    badges = f' <span class="pub-badges">{"".join(badges)}</span>' if badges else ""

    chips = []
    if p.get("url"):
        chips.append((p["url"], link_label(p["url"])))
    for key, label in (("pdf", "PDF"), ("code", "Code"), ("project", "Project page"),
                       ("poster", "Poster"), ("slides", "Slides")):
        if p.get(key):
            chips.append((p[key], label))
    chip_html = [
        f'<a class="chip" href="{escape(href)}" target="_blank" rel="noopener noreferrer">{label}</a>'
        for href, label in chips
    ]
    player = None
    if p.get("video"):
        vid = youtube_id(p["video"])
        player = f"player-{slug(p['title'])}"
        chip_html.append(
            f'<a class="chip" href="https://www.youtube.com/watch?v={escape(vid)}" data-yt="{escape(vid)}" '
            f'data-title="{escape(p["title"])}" aria-controls="{player}" aria-expanded="false" '
            f'target="_blank" rel="noopener noreferrer">▶ Video</a>'
        )

    cls = "pub has-teaser" if p.get("teaser") else "pub"
    lines = [
        f'{i1}<li class="{cls}">',
        f'{i2}<span class="pub-year">{p["year"]}</span>',
        f"{i2}<div>",
        f'{i3}<{heading} class="pub-title">{title}</{heading}>',
    ]
    if summary and p.get("summary"):
        lines.append(f'{i3}<p class="pub-summary">{escape(p["summary"])}</p>')
    lines += [
        f'{i3}<p class="pub-authors">{authors}</p>',
        f'{i3}<p class="pub-venue">{escape(p.get("web_venue", p["venue"]))}{badges}</p>',
    ]
    if chip_html:
        lines.append(f'{i3}<div class="chips">' + "".join(chip_html) + "</div>")
    if player:
        lines.append(f'{i3}<div class="pub-player" id="{player}" hidden></div>')
    lines.append(f"{i2}</div>")
    if p.get("teaser"):
        lines.append(teaser(p["teaser"], i2))
    lines.append(f"{i1}</li>")
    return "\n".join(lines)


def group(title, pubs, default_tag=None):
    items = "\n".join(pub_item(p, default_tag, indent="                        ", heading="h4") for p in pubs)
    return (
        '                <div class="pub-group">\n'
        f'                    <h3 class="pub-group-title">{title}</h3>\n'
        '                    <ol class="pub-list">\n'
        f"{items}\n"
        "                    </ol>\n"
        "                </div>\n"
    )


def selected_publications(data):
    featured = [(p, "Preprint") for p in data["preprints"] if p.get("featured")]
    featured += [(p, None) for p in data["peer_reviewed"] if p.get("featured")]
    featured.sort(key=lambda x: (-x[0]["year"], x[1] is not None))   # newest first, published before preprints
    items = "\n".join(pub_item(p, tag, summary=True, indent="                    ") for p, tag in featured)
    return (
        '                <ol class="pub-list">\n'
        f"{items}\n"
        "                </ol>\n"
    )


def media_section(items):
    if not items:
        return ""
    cards = []
    for m in items:
        vid = youtube_id(m["youtube"])
        where = " · ".join(escape(str(m[k])) for k in ("kind", "venue", "date") if m.get(k))
        cards.append(
            '                    <article class="media-item">\n'
            f'                        <a class="video" href="https://www.youtube.com/watch?v={escape(vid)}" data-yt="{escape(vid)}" '
            f'aria-label="Play: {escape(m["title"])}" target="_blank" rel="noopener noreferrer">\n'
            f'                            <img src="https://i.ytimg.com/vi/{escape(vid)}/hqdefault.jpg" alt="" loading="lazy">\n'
            '                            <span class="play"></span>\n'
            "                        </a>\n"
            f'                        <h3>{escape(m["title"])}</h3>\n'
            + (f"                        <p>{where}</p>\n" if where else "")
            + "                    </article>"
        )
    return (
        '        <section class="section" id="media">\n'
        '            <h2 class="section-title">Talks &amp; media</h2>\n'
        '            <div class="section-body">\n'
        '                <div class="media-grid">\n'
        + "\n".join(cards)
        + "\n                </div>\n"
        "            </div>\n"
        "        </section>\n"
    )


def replace_block(html, name, content):
    pattern = re.compile(rf"(<!-- BEGIN {name} -->\n).*?(\s*<!-- END {name} -->)", re.S)
    if not pattern.search(html):
        raise SystemExit(f"index.html is missing the '{name}' markers")
    return pattern.sub(lambda m: m.group(1) + content.rstrip("\n") + m.group(2), html)


def main():
    data = yaml.safe_load((ROOT / "cv" / "publications.yaml").read_text(encoding="utf-8"))
    media = yaml.safe_load((ROOT / "cv" / "media.yaml").read_text(encoding="utf-8")) or {}

    html = (
        HEAD
        + group("Preprints &amp; under review", data["preprints"], default_tag="Preprint")
        + group("Peer-reviewed", data["peer_reviewed"])
        + FOOT
    )
    (ROOT / "publications.html").write_text(html, encoding="utf-8")

    index_path = ROOT / "index.html"
    index = index_path.read_text(encoding="utf-8")
    index = replace_block(index, "selected-publications", selected_publications(data))
    index = replace_block(index, "media", media_section(media.get("media") or []))
    index_path.write_text(index, encoding="utf-8")


if __name__ == "__main__":
    main()
